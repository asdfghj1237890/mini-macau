import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import sharp from 'sharp'

// The illustrated master lives outside public/. Rebuild all platform icons with
// npm run icons:pwa after replacing it. Keep the facade's illustrated detail in the
// master; resize only at export. sharp is supplied by wrangler's miniflare.
const root = resolve(import.meta.dirname, '..')
const source = readFileSync(resolve(root, 'assets/app-icon/ruins-material.png'))
const background = '#1c2729'
const outDir = resolve(root, 'public/pwa')
const metadata = await sharp(source).metadata()
if (metadata.width !== metadata.height || metadata.width < 512) {
  throw new Error('The app icon master must be square and at least 512 px')
}

// The master includes its dark background. Frame it on that same colour.
// At 64 %, shifting the broad base up 3 % keeps the complete facade and steps
// inside the maskable 80 % circle while giving the cross enough headroom.
async function render(px, scale, rounded = false, shiftY = 0) {
  const artSize = Math.round(px * scale)
  const inset = Math.floor((px - artSize) / 2)
  const art = await sharp(source).resize(artSize, artSize).png().toBuffer()
  const tile = await sharp({ create: { width: px, height: px, channels: 4, background } })
    .composite([{ input: art, left: inset, top: inset + Math.round(px * shiftY) }])
    .png().toBuffer()
  const result = sharp(tile)
  if (rounded) {
    const mask = `<svg width="${px}" height="${px}"><rect width="${px}" height="${px}" rx="${px * .22}" fill="white"/></svg>`
    result.composite([{ input: Buffer.from(mask), blend: 'dest-in' }])
  }
  return result.png({ palette: true, colours: 256, dither: 0 }).toBuffer()
}

const targets = [
  ['icon-192.png', 192, .9, true],
  ['icon-512.png', 512, .9, true],
  ['maskable-192.png', 192, .64, false, -.03],
  ['maskable-512.png', 512, .64, false, -.03],
  ['apple-touch-icon-180.png', 180, .9, false],
]

mkdirSync(outDir, { recursive: true })
for (const [name, px, scale, rounded, shiftY] of targets) {
  const png = await render(px, scale, rounded, shiftY)
  writeFileSync(resolve(outDir, name), png)
  console.log(`${name}\t${px}×${px}\t${png.length} bytes`)
}

// Preserve the existing favicon URL, using a self-contained raster illustration
// inside the SVG wrapper. The editable master is the PNG above, not this export.
const favicon = await render(128, .9, true)
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128">
  <title>Mini Macau — Ruins of St. Paul's</title>
  <!-- Generated by npm run icons:pwa from assets/app-icon/ruins-material.png. -->
  <image width="128" height="128" href="data:image/png;base64,${favicon.toString('base64')}"/>
</svg>
`
writeFileSync(resolve(root, 'public/favicon.svg'), svg)
console.log(`favicon.svg\t128×128 embedded illustration\t${Buffer.byteLength(svg)} bytes`)
